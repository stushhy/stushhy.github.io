/**
 * @input
 * 에러 코렉션 블럭 수: n (>=2)
 * @output
 * 해당 generator 다항식의 지수 계수
 */
function ECP(n){
    //재귀함수로 짜야되나
    if(n<2){
        throw new Error(`에러 다항식 인풋이 이상해요. n:${n}`);
    } else if (n === 2){
        return [0, 25, 1]
    }
    else {
        let result = [];
        let mul = [0, n-1];
        let prev = ECP(n-1);

        //0번째 작업 해주기 (반복 안에 넣으면 쓸데없이 if 추가되니까,..) 모듈러 연산을 if 통해서 해도 되는데, 그냥 해도 상관없지 않나. if랑 모듈러랑 자원소모 따져보든가;
        result.push((prev[0]+mul[0])%255);
        result.push((prev[0]+mul[1])%255);
        /**
         * 반복 작업 시작.
         * 1. 이전 다항식의 계수를 기준으로, 처음 애부터 mul이랑 각각 곱하고 그걸 겹쳐서 넣고.
         * 2. 겹칠 때는 첫 항과 result의 마지막 항과 겹치는 건데, 우선 겹치기 전에 각 지수에 mod 255 해주고,
         * 3. 지수에서정수로, XOR, 정수에서지수로.
         */
        for(let i=1;i<prev.length;i++){
            result[result.length-1] = 정수에서지수로[지수에서정수로[result[result.length-1]] ^ 지수에서정수로[(prev[i] + mul[0])%255]];
            result.push((prev[i]+mul[1])%255);
        }
        return result;
    }
}

